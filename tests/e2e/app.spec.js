import {test,expect} from "@playwright/test";
const pass="a-long-private-testing-passphrase";
test("encrypted check-in survives lock, reload and can be edited",async({page})=>{
  await page.goto("/");
  await expect(page.getByText("Your space, your pace.")).toBeVisible();
  await page.locator("#passphrase").fill(pass);
  await page.locator("#confirm-passphrase").fill(pass);
  await page.locator("#consent").check();
  await page.locator("#auth-submit").click();
  await expect(page.locator("#app-shell")).toBeVisible();
  await page.getByRole("button",{name:"Daily check-in"}).click();
  await page.locator('[data-mood="4"]').click();
  await page.locator("#sleep-hours").fill("6.5");
  await page.locator("#exercise-min").fill("25");
  await page.locator("#stress-level").selectOption("2");
  await page.locator("#entry-note").fill("Grateful for a calm afternoon.");
  await page.locator("#save-entry").click();
  await expect(page.locator("#stat-entries")).toHaveText("1");
  const stored=await page.evaluate(()=>localStorage.getItem("mood-insight-vault-v1"));
  expect(stored).toBeTruthy();
  expect(stored).not.toContain("Grateful for a calm afternoon.");
  await page.getByRole("button",{name:"My journal"}).click();
  await expect(page.getByText("Grateful for a calm afternoon.")).toBeVisible();
  await page.getByRole("button",{name:"Edit"}).click();
  await page.locator('[data-mood="5"]').click();
  await page.locator("#save-entry").click();
  await expect(page.locator("#stat-average")).toHaveText("5.0");
  await page.locator("#lock-button").click();
  await page.reload();
  await page.locator("#passphrase").fill(pass);
  await page.locator("#auth-submit").click();
  await expect(page.locator("#stat-entries")).toHaveText("1");
  await page.getByRole("button",{name:"My journal"}).click();
  await expect(page.locator("#history-list")).toContainText("Great");
});
test("mobile navigation is usable without horizontal overflow",async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto("/");
  await page.locator("#passphrase").fill(pass);
  await page.locator("#confirm-passphrase").fill(pass);
  await page.locator("#consent").check();
  await page.locator("#auth-submit").click();
  await page.locator("#menu-toggle").click();
  await expect(page.locator("#sidebar")).toHaveClass(/open/);
  await page.locator('#sidebar [data-view="checkin"]').click();
  await expect(page.locator("#view-checkin")).toBeVisible();
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth);
  expect(overflow).toBeLessThanOrEqual(2);
});
